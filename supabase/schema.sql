-- =====================================================================
-- CÉREBRO PCMA — banco do ranking (Supabase / PostgreSQL)
-- Equivalente à tabela "rankings" do Cloudflare D1 do site original.
-- Os visitantes não acessam as tabelas diretamente: tudo passa pelas
-- funções abaixo (o gabarito e as respostas individuais ficam protegidos).
-- =====================================================================

create table if not exists public.rankings (
  id bigint generated by default as identity primary key,
  exam_id text not null,
  attempt_key text not null,
  candidate_name text not null,
  score integer not null,
  total integer not null,
  elapsed_seconds integer not null,
  answers_json text not null,
  finished_at text not null
);
create unique index if not exists idx_rankings_exam_attempt on public.rankings (exam_id, attempt_key);
create index if not exists idx_rankings_exam_score_time on public.rankings (exam_id, score desc, elapsed_seconds asc, finished_at asc);

create table if not exists public.exams (
  id text primary key,
  duration_seconds integer not null,
  is_maranhao boolean not null default false,
  number integer not null,
  previous_id text
);

create table if not exists public.gabaritos (
  exam_id text not null references public.exams(id),
  n integer not null,
  g text not null,
  primary key (exam_id, n)
);

alter table public.rankings enable row level security;
alter table public.exams enable row level security;
alter table public.gabaritos enable row level security;
revoke all on public.rankings, public.exams, public.gabaritos from anon, authenticated;

-- Revisão vigente da Temporada Maranhão (MARANHAO_REVISION do original).
create or replace function public.maranhao_revision() returns text
language sql immutable as $$ select 'ma20261016'::text $$;

-- Ranking de um simulado: acertos desc, tempo asc, data asc (como no original).
create or replace function public.get_ranking(p_exam text, p_limit integer default 100)
returns table (candidate_name text, score integer, total integer, elapsed_seconds integer, finished_at text)
language sql stable security definer set search_path = public as $$
  select r.candidate_name, r.score, r.total, r.elapsed_seconds, r.finished_at
  from rankings r
  where r.exam_id = p_exam
  order by r.score desc, r.elapsed_seconds asc, r.finished_at asc, r.id asc
  limit least(greatest(coalesce(p_limit, 100), 1), 100);
$$;

-- Entregas de um candidato (para o "Progresso semanal"). Devolve só a contagem
-- de respostas, nunca as respostas em si.
create or replace function public.candidate_attempts(p_name text)
returns table (candidate_name text, answered integer, finished_at text)
language sql stable security definer set search_path = public as $$
  select r.candidate_name,
         (select count(*)::integer
            from json_each_text(case when left(btrim(r.answers_json), 1) = '{' then r.answers_json::json else '{}'::json end) e
           where e.key ~ '^([1-9]|[1-9][0-9]|100)$' and e.value ~* '^[a-e]$'),
         r.finished_at
  from rankings r
  where lower(r.candidate_name) = lower(regexp_replace(btrim(p_name), '\s+', ' ', 'g'))
  order by r.finished_at asc, r.id asc;
$$;

create or replace function public.has_completed(p_name text, p_exam text)
returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from rankings
    where lower(candidate_name) = lower(left(regexp_replace(btrim(p_name), '\s+', ' ', 'g'), 40))
      and exam_id = p_exam
  );
$$;

-- Entrega da prova: valida, corrige pelo gabarito do servidor e registra.
-- Mesmo comportamento de app/api/attempts/finish/route.ts.
create or replace function public.finish_attempt(
  p_exam text, p_attempt_key text, p_name text, p_elapsed integer, p_answers jsonb
) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_exam exams%rowtype;
  v_name text;
  v_answers json;
  v_total integer;
  v_score integer;
  v_elapsed integer;
  v_row rankings%rowtype;
  v_position integer;
begin
  select * into v_exam from exams where id = p_exam;
  v_name := left(regexp_replace(btrim(coalesce(p_name, '')), '\s+', ' ', 'g'), 40);
  if v_exam.id is null
     or p_attempt_key is null or p_attempt_key !~ '^[a-zA-Z0-9-]{16,80}$'
     or char_length(v_name) < 2
     or p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    raise exception '400: Não foi possível validar esta entrega.';
  end if;

  if v_exam.is_maranhao and left(p_attempt_key, char_length(maranhao_revision()) + 1) <> maranhao_revision() || '-' then
    raise exception '409: Este simulado foi atualizado. Recarregue a página para iniciar a nova versão.';
  end if;
  if v_exam.is_maranhao and v_exam.previous_id is not null and not has_completed(v_name, v_exam.previous_id) then
    raise exception '403: Conclua primeiro o Simulado % usando este mesmo nome.', v_exam.number - 1;
  end if;

  select * into v_row from rankings where exam_id = p_exam and attempt_key = p_attempt_key;

  if v_row.id is null then
    select coalesce(json_object_agg(e.key, lower(e.value) order by e.key::integer), '{}'::json)
      into v_answers
      from jsonb_each_text(p_answers) e
     where e.key ~ '^([1-9]|[1-9][0-9]|100)$' and e.value ~* '^[a-e]$';

    select count(*), count(*) filter (where (v_answers ->> g.n::text) = lower(g.g))
      into v_total, v_score
      from gabaritos g where g.exam_id = p_exam;

    v_elapsed := greatest(0, least(v_exam.duration_seconds, coalesce(p_elapsed, v_exam.duration_seconds)));

    insert into rankings (exam_id, attempt_key, candidate_name, score, total, elapsed_seconds, answers_json, finished_at)
    values (p_exam, p_attempt_key, v_name, v_score, v_total, v_elapsed, v_answers::text,
            to_char(clock_timestamp() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
    on conflict (exam_id, attempt_key) do nothing;

    select * into v_row from rankings where exam_id = p_exam and attempt_key = p_attempt_key;
  end if;

  select x.pos into v_position from (
    select r.candidate_name, r.score, r.finished_at,
           row_number() over (order by r.score desc, r.elapsed_seconds asc, r.finished_at asc, r.id asc) as pos
    from rankings r where r.exam_id = p_exam
    order by pos limit 100
  ) x
  where x.candidate_name = v_row.candidate_name and x.score = v_row.score and x.finished_at = v_row.finished_at
  order by x.pos limit 1;

  return json_build_object(
    'exam_id', v_row.exam_id,
    'candidate_name', v_row.candidate_name,
    'score', v_row.score,
    'total', v_row.total,
    'elapsed_seconds', v_row.elapsed_seconds,
    'answers_json', v_row.answers_json,
    'finished_at', v_row.finished_at,
    'position', v_position
  );
end;
$$;

revoke all on function public.get_ranking(text, integer), public.candidate_attempts(text),
  public.has_completed(text, text), public.finish_attempt(text, text, text, integer, jsonb) from public;
grant execute on function public.get_ranking(text, integer), public.candidate_attempts(text),
  public.has_completed(text, text), public.finish_attempt(text, text, text, integer, jsonb) to anon, authenticated;
